-- Holy Matrimony
-- V42: India geography and district-franchise foundation
--
-- Geography source:
-- Government of India Local Government Directory (LGD).
-- State/UT and district records were captured and validated
-- from the live LGD district service before this migration
-- was generated.
--
-- Franchise hierarchy:
-- HQ -> India -> State/UT -> District Franchise -> Territory
--
-- Important domain rules:
-- 1. State/UT is an HQ geography/analytics grouping.
-- 2. There is no State Franchise in this model.
-- 3. A district may have at most one active franchise allocation.
-- 4. Territories are operational children of a district franchise.
-- 5. Geographic scope and financial attribution remain separate.

CREATE EXTENSION IF NOT EXISTS pgcrypto;

-- =========================================================
-- GEOGRAPHY: STATES / UNION TERRITORIES
-- =========================================================

CREATE TABLE geo_states (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    lgd_code INTEGER NOT NULL UNIQUE,
    name VARCHAR(150) NOT NULL,
    country_code VARCHAR(2) NOT NULL DEFAULT 'IN',
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT uq_geo_states_name
        UNIQUE (name)
);

