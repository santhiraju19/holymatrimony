-- =========================================================
-- FRANCHISE
-- =========================================================

CREATE TABLE franchises (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    franchise_code VARCHAR(40) NOT NULL UNIQUE,
    legal_name VARCHAR(200) NOT NULL,
    display_name VARCHAR(200) NOT NULL,
    status VARCHAR(40) NOT NULL,
    contact_name VARCHAR(150),
    contact_email VARCHAR(180),
    contact_mobile VARCHAR(30),
    activated_at TIMESTAMP,
    suspended_at TIMESTAMP,
    terminated_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT chk_franchises_status CHECK (
        status IN (
            'APPLICATION',
            'UNDER_REVIEW',
            'APPROVED',
            'AGREEMENT_PENDING',
            'ONBOARDING',
            'ACTIVE',
            'SUSPENDED',
            'EXPIRED',
            'TERMINATED',
            'REJECTED'
        )
    )
);

CREATE INDEX idx_franchises_status
    ON franchises(status);

-- =========================================================
-- DISTRICT <-> FRANCHISE ALLOCATION
-- =========================================================

-- This table owns district assignment history.
-- Franchise itself does not duplicate authorization geography.

CREATE TABLE franchise_district_allocations (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    franchise_id UUID NOT NULL,
    district_id UUID NOT NULL,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    allocated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at TIMESTAMP,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_franchise_district_allocation_franchise
        FOREIGN KEY (franchise_id)
        REFERENCES franchises(id),

    CONSTRAINT fk_franchise_district_allocation_district
        FOREIGN KEY (district_id)
        REFERENCES geo_districts(id),

    CONSTRAINT chk_franchise_district_allocation_dates CHECK (
        ended_at IS NULL
        OR ended_at >= allocated_at
    )
);

-- Core business invariant:
-- exactly zero or one active District Franchise per district.

CREATE UNIQUE INDEX uq_active_franchise_per_district
    ON franchise_district_allocations(district_id)
    WHERE active = TRUE;

-- A District Franchise represents one district while active.
-- Prevent one active franchise record from owning multiple districts.

CREATE UNIQUE INDEX uq_active_district_per_franchise
    ON franchise_district_allocations(franchise_id)
    WHERE active = TRUE;

CREATE INDEX idx_franchise_district_allocations_franchise
    ON franchise_district_allocations(franchise_id);

CREATE INDEX idx_franchise_district_allocations_district
    ON franchise_district_allocations(district_id);

-- =========================================================
-- FRANCHISE TERRITORIES
-- =========================================================

-- Territories are operational children inside the allocated
-- district. They are not independent franchises.

CREATE TABLE franchise_territories (
    id UUID PRIMARY KEY DEFAULT gen_random_uuid(),
    district_allocation_id UUID NOT NULL,
    territory_code VARCHAR(60) NOT NULL,
    name VARCHAR(180) NOT NULL,
    territory_type VARCHAR(40) NOT NULL,
    coverage_description TEXT,
    active BOOLEAN NOT NULL DEFAULT TRUE,
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,

    CONSTRAINT fk_franchise_territory_allocation
        FOREIGN KEY (district_allocation_id)
        REFERENCES franchise_district_allocations(id),

    CONSTRAINT chk_franchise_territory_type CHECK (
        territory_type IN (
            'CITY',
            'MUNICIPALITY',
            'MANDAL',
            'TALUK',
            'PIN_CLUSTER',
            'CUSTOM'
        )
    ),

    CONSTRAINT uq_franchise_territory_code
        UNIQUE (district_allocation_id, territory_code),

    CONSTRAINT uq_franchise_territory_name
        UNIQUE (district_allocation_id, name)
);

CREATE INDEX idx_franchise_territories_allocation
    ON franchise_territories(district_allocation_id);

CREATE INDEX idx_franchise_territories_active
    ON franchise_territories(active);
